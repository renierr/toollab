DevicePattern? matchDevicePattern(String name) {
  if (name.isEmpty || name == 'Unknown') return null;
  for (final dp in devicePatterns) {
    try {
      final re = RegExp(dp.pattern, caseSensitive: false);
      if (re.hasMatch(name)) return dp;
    } catch (_) {}
  }
  return null;
}
